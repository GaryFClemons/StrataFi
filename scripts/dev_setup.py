#!/usr/bin/env python3
"""Set up this machine for development. Safe to run again at any time.

    uv run python scripts/dev_setup.py

- Writes the development signing key pair for identity tokens to data/keys/.
- Builds .env from .env.example. A value of __GENERATE_SECRET__ gets a random secret the first
  time and keeps it on later runs; ${NAME} in a value is replaced with another variable's
  value. Existing values in .env are kept.
- In a git worktree, also sets COMPOSE_PROJECT_NAME (stratafi-<folder>), so the worktree gets
  its own containers and volumes; the main checkout keeps compose.yaml's `name: stratafi`.

Mint a development token (refused when STRATAFI_ENV=prod):

    uv run python scripts/dev_setup.py token --tenant local --user owner
    uv run python scripts/dev_setup.py token --tenant halcyon --sub u-me --roles editor,viewer

``--user`` takes a synthetic user's role: owner, editor, viewer or guest. The token is printed
alone on stdout, so ``TOKEN=$(...)`` works. Send it as the ``X-Stratafi-Identity`` header. It
lasts at most five minutes.
"""

import argparse
import os
import re
import secrets
import sys
from pathlib import Path

from stratafi_core.envfile import format_env_value, parse_env, read_env_file
from stratafi_core.identity import MAX_TTL_SECONDS, IdentityError, TokenSigner, generate_keypair

ROOT = Path(__file__).resolve().parent.parent
GENERATE = "__GENERATE_SECRET__"
PROJECT_KEY = "COMPOSE_PROJECT_NAME"
SIGNING_KEY = Path("data/keys/identity-signing.pem")
PUBLIC_KEY = Path("data/keys/identity-signing.pub.pem")
_REFERENCE_RE = re.compile(r"\$\{([A-Za-z_][A-Za-z0-9_]*)\}")


def compose_project_name(root: Path) -> str | None:
    """stratafi-<folder> for a git worktree; None for the main checkout."""
    # A linked worktree has a .git file pointing at the main repository; the main checkout has a
    # .git directory.
    if not (root / ".git").is_file():
        return None
    slug = re.sub(r"[^a-z0-9]+", "-", root.name.lower()).strip("-").removeprefix("stratafi-")
    return f"stratafi-{slug}" if slug and slug != "stratafi" else "stratafi-worktree"


def build_env(
    root: Path, existing: dict[str, str]
) -> tuple[list[tuple[str, list[tuple[str, str]]]], dict[str, int]]:
    """Merge .env.example with an existing .env. Returns sections of (key, value) and counts."""
    counts = {"generated": 0, "kept": 0}
    entries: list[tuple[str, str]] = []
    from_example: set[str] = set()
    seen: set[str] = set()
    for key, value in parse_env((root / ".env.example").read_text(encoding="utf-8")):
        if key in seen:
            continue
        seen.add(key)
        if key in existing:
            final = existing[key]
            counts["kept"] += 1
        elif value == GENERATE:
            final = secrets.token_urlsafe(32)
            counts["generated"] += 1
        else:
            final = value
            from_example.add(key)
        entries.append((key, final))

    values = dict(entries)

    def expand(key: str, depth: int = 0) -> str:
        if depth > 10:
            raise SystemExit(f"dev_setup: {key} has a ${{...}} reference loop")

        def substitute(match: re.Match[str]) -> str:
            name = match.group(1)
            if name not in values:
                raise SystemExit(f"dev_setup: {key} refers to ${{{name}}}, which isn't defined")
            return expand(name, depth + 1) if name in from_example else values[name]

        return _REFERENCE_RE.sub(substitute, values[key])

    entries = [(key, expand(key) if key in from_example else value) for key, value in entries]
    sections = [(".env.example", entries)]
    project = compose_project_name(root)
    if project is not None and PROJECT_KEY not in seen:
        seen.add(PROJECT_KEY)
        note = "this checkout (a git worktree gets its own containers and volumes)"
        sections.append((note, [(PROJECT_KEY, existing.get(PROJECT_KEY, project))]))
    extra = [(key, value) for key, value in existing.items() if key not in seen]
    if extra:
        sections.append(("the previous .env (not in .env.example)", extra))
    return sections, counts


def write_env(path: Path, sections: list[tuple[str, list[tuple[str, str]]]]) -> None:
    lines = [
        "# Generated by scripts/dev_setup.py from .env.example. Never commit this file.",
        "# Edit values here if you need to; re-running dev_setup.py keeps them.",
    ]
    for source, entries in sections:
        lines += ["", f"# --- from {source}"]
        lines += [f"{key}={format_env_value(value)}" for key, value in entries]
    data = ("\n".join(lines) + "\n").encode("utf-8")
    flags = os.O_WRONLY | os.O_CREAT | os.O_TRUNC | getattr(os, "O_BINARY", 0)
    with os.fdopen(os.open(path, flags, 0o600), "wb") as handle:
        handle.write(data)


def setup(root: Path) -> int:
    private_key = root / SIGNING_KEY
    if private_key.exists():
        print(f"identity signing key: kept {SIGNING_KEY.as_posix()}")
    else:
        kid = generate_keypair(private_key, root / PUBLIC_KEY)
        print(f"identity signing key: wrote {SIGNING_KEY.as_posix()} (kid {kid})")

    env_path = root / ".env"
    existing = read_env_file(env_path) if env_path.is_file() else {}
    sections, counts = build_env(root, existing)
    write_env(env_path, sections)
    total = sum(len(entries) for _, entries in sections)
    print(
        f".env: {total} variables ({counts['generated']} new secrets, {counts['kept']} kept) "
        "from .env.example"
    )
    project = dict(entry for _, entries in sections for entry in entries).get(
        PROJECT_KEY, "stratafi"
    )
    print(f"docker compose project: {project}")
    return 0


def mint_token(root: Path, args: argparse.Namespace) -> int:
    if os.environ.get("STRATAFI_ENV") == "prod":
        print("dev_setup: refusing to mint dev tokens when STRATAFI_ENV=prod", file=sys.stderr)
        return 2
    key_path = Path(args.key) if args.key else root / SIGNING_KEY
    if not key_path.is_file():
        print(
            "dev_setup: no signing key; run `uv run python scripts/dev_setup.py` first",
            file=sys.stderr,
        )
        return 2
    signer = TokenSigner.from_file(key_path)
    try:
        if args.user:
            from stratafi_testing.users import synthetic_user

            user = synthetic_user(args.tenant, args.user)
            sub, roles, groups = user.user_id, user.roles, user.groups
        else:
            sub, roles, groups = args.sub, (), ()
        token = signer.mint(
            sub=sub,
            tenant=args.tenant,
            roles=args.roles.split(",") if args.roles else roles,
            groups=args.groups.split(",") if args.groups else groups,
            ttl=args.ttl,
        )
    except (IdentityError, KeyError) as exc:
        print(f"dev_setup: can't mint that token ({exc})", file=sys.stderr)
        return 2
    print(token)
    return 0


def main(argv: list[str] | None = None, *, root: Path = ROOT) -> int:
    parser = argparse.ArgumentParser(description="Set up this machine for development.")
    commands = parser.add_subparsers(dest="command")
    token = commands.add_parser("token", help="mint a development identity token")
    token.add_argument("--tenant", required=True, help="the tenant (tid), such as local")
    who = token.add_mutually_exclusive_group(required=True)
    who.add_argument("--user", help="a synthetic user's role: owner, editor, viewer or guest")
    who.add_argument("--sub", help="any subject, with --roles and --groups")
    token.add_argument("--roles", help="comma-separated roles, replacing the user's")
    token.add_argument("--groups", help="comma-separated groups, replacing the user's")
    token.add_argument("--ttl", type=int, default=MAX_TTL_SECONDS, help="seconds, at most 300")
    token.add_argument("--key", help=f"signing key (default {SIGNING_KEY.as_posix()})")
    args = parser.parse_args(argv)
    if args.command == "token":
        return mint_token(root, args)
    return setup(root)


if __name__ == "__main__":
    sys.exit(main())
